package com.example.apppet;

public class Animale {
    String nome;
    float peso;
    float altezza;
    String note;
    boolean sesso;
    String dataNascita;

    public Animale(String nome, float peso, float altezza, String note, boolean sesso, String dataNascita) {
        this.nome = nome;
        this.peso = peso;
        this.altezza = altezza;
        this.note = note;
        this.sesso = sesso;
        this.dataNascita = dataNascita;
    }
}
